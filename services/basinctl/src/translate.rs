/// Double-quote an identifier, doubling internal quotes. Used for both ends
/// (Basin's COPY/DDL paths accept double-quoted identifiers).
pub fn quote_ident(name: &str) -> String {
    format!("\"{}\"", name.replace('"', "\"\""))
}

/// Single-quote a string literal, doubling internal quotes.
pub fn quote_literal(s: &str) -> String {
    format!("'{}'", s.replace('\'', "''"))
}

