//! Pure PostgreSQL → Basin DDL translation for `basinctl import-from-postgres`.
//!
//! Everything in this module is deterministic and network-free: it takes the
//! introspected source model (`SourceTable` / `SourceColumn` / `EnumType`,
//! filled in by `import::introspect`) and produces per-table [`TablePlan`]s —
//! Basin `CREATE TABLE` SQL, the PG-side `SELECT` projection used by `COPY
//! (SELECT …) TO STDOUT`, the binary-vs-CSV transfer decision, plus a
//! [`Report`] of skipped objects and warnings.
//!
//! ## Type-mapping ground rules
//!
//! - The Basin dialect is whatever `basin_engine::types::arrow_data_type`
//!   accepts (see that match for the canonical list). We never emit a type
//!   name that function rejects.
//! - `serial` / `bigserial` / `smallserial` (detected via a
//!   `nextval('…')` column default) normalise to
//!   `BIGINT GENERATED BY DEFAULT AS IDENTITY` — Basin's identity
//!   convention — with a PG-side `::int8` cast so the binary COPY stream
//!   carries int8, matching the widened target column.
//! - Extension-backed types Basin understands natively (`uuid`, `jsonb`,
//!   `citext`, `vector(N)`) pass straight through.
//! - "Binary-safe" means the *source* type's PG binary COPY wire format is
//!   exactly what Basin's binary COPY decoder expects for the *mapped*
//!   column type (the intersection enforced by
//!   `basin_router::copy::validate_binary_copy_columns`). Everything else
//!   rides the CSV fallback; a single non-binary-safe column flips the
//!   whole table to CSV (COPY is per-table, not per-column).
//! - Unsupported features are *skipped loudly*, never silently: each skip
//!   lands in [`Report::skips`] with a reason and a migration hint
//!   (triggers → Basin reactors, plpgsql → WASM functions, EXCLUDE → manual).

use std::collections::{BTreeMap, HashMap, HashSet};
use std::fmt::Write as _;

// ---------------------------------------------------------------------------
// Source model (filled by import::introspect)
// ---------------------------------------------------------------------------

/// One `CREATE TYPE … AS ENUM` on the source, with labels in sort order.
#[derive(Debug, Clone)]
pub struct EnumType {
    pub schema: String,
    pub name: String,
    pub labels: Vec<String>,
}

/// `GENERATED { ALWAYS | BY DEFAULT } AS IDENTITY` flavour.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum IdentityKind {
    Always,
    ByDefault,
}

/// One column as seen through `information_schema.columns` joined with
/// `pg_catalog` (for `format_type` and `typtype` — information_schema alone
/// loses vector dims and the enum/composite distinction).
#[derive(Debug, Clone, Default)]
pub struct SourceColumn {
    pub name: String,
    /// `information_schema.columns.data_type` (e.g. `ARRAY`, `USER-DEFINED`).
    pub data_type: String,
    /// `information_schema.columns.udt_name` (e.g. `int4`, `_text`, `vector`).
    pub udt_name: String,
    /// `format_type(atttypid, atttypmod)` — carries modifiers: `vector(384)`,
    /// `numeric(10,2)`, `geometry(Point,4326)`.
    pub formatted_type: String,
    /// `pg_type.typtype`: `b` base, `e` enum, `c` composite, `d` domain,
    /// `r`/`m` range, `p` pseudo.
    pub typtype: String,
    /// For arrays: the element's udt_name (leading `_` stripped) + typtype.
    pub elem_udt: Option<String>,
    pub elem_typtype: Option<String>,
    pub max_len: Option<i32>,
    pub num_precision: Option<i32>,
    pub num_scale: Option<i32>,
    pub not_null: bool,
    pub default: Option<String>,
    pub identity: Option<IdentityKind>,
    /// `GENERATED ALWAYS AS (expr) STORED` expression, if any.
    pub generated_expr: Option<String>,
    /// Set when the column's declared type is a domain (we map the
    /// underlying type and warn).
    pub domain_name: Option<String>,
}

#[derive(Debug, Clone)]
pub struct SourceUnique {
    pub name: String,
    pub columns: Vec<String>,
}

#[derive(Debug, Clone)]
pub struct SourceCheck {
    pub name: String,
    /// `information_schema.check_constraints.check_clause` (bare boolean
    /// expression, no `CHECK` keyword).
    pub clause: String,
}

#[derive(Debug, Clone)]
pub struct SourceFk {
    pub name: String,
    pub columns: Vec<String>,
    pub ref_schema: String,
    pub ref_table: String,
    pub ref_columns: Vec<String>,
    /// `referential_constraints.delete_rule` / `update_rule`
    /// (`NO ACTION` / `CASCADE` / `SET NULL` / `SET DEFAULT` / `RESTRICT`).
    pub on_delete: String,
    pub on_update: String,
}

#[derive(Debug, Clone)]
pub struct SourceTable {
    pub schema: String,
    pub name: String,
    pub columns: Vec<SourceColumn>,
    pub primary_key: Vec<String>,
    pub uniques: Vec<SourceUnique>,
    pub checks: Vec<SourceCheck>,
    pub fks: Vec<SourceFk>,
}

impl SourceTable {
    pub fn qualified(&self) -> String {
        format!("{}.{}", self.schema, self.name)
    }
}

