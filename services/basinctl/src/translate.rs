/// One object the importer refused to carry over. Printed per-object during
/// the run (loud) and aggregated in the final summary.
#[derive(Debug, Clone)]
pub struct Skip {
    /// `table` / `column` / `constraint` / `trigger` / `function` / `view` /
    /// `materialized view` / `type`.
    pub kind: &'static str,
    /// Schema-qualified object name (`public.users.audit_trg`).
    pub object: String,
    pub reason: String,
    /// What to do instead, when Basin has an answer.
    pub hint: Option<String>,
}

impl Skip {
    pub fn render(&self) -> String {
        let mut s = format!("SKIP {:<10} {} — {}", self.kind, self.object, self.reason);
        if let Some(h) = &self.hint {
            let _ = write!(s, " ({h})");
        }
        s
    }
}

/// Collected skips + soft warnings for the whole import.
#[derive(Debug, Clone, Default)]
pub struct Report {
    pub skips: Vec<Skip>,
    pub warnings: Vec<String>,
}

impl Report {
    pub fn skip(
        &mut self,
        kind: &'static str,
        object: impl Into<String>,
        reason: impl Into<String>,
        hint: Option<&str>,
    ) {
        let s = Skip {
            kind,
            object: object.into(),
            reason: reason.into(),
            hint: hint.map(str::to_owned),
        };
        // Loud, immediate, per-object — the summary repeats it at the end.
        eprintln!("{}", s.render());
        self.skips.push(s);
    }

    pub fn warn(&mut self, msg: impl Into<String>) {
        let m = msg.into();
        eprintln!("WARN {m}");
        self.warnings.push(m);
    }
}

