    #[test]
    fn create_ladder_drops_checks_then_fks() {
        let mut t = table("t", vec![col("id", "int8"), col("p_id", "int8")]);
        t.checks = vec![SourceCheck {
            name: "t_pos".to_owned(),
            clause: "id > 0".to_owned(),
        }];
        t.fks = vec![SourceFk {
            name: "t_p_fkey".to_owned(),
            columns: vec!["p_id".to_owned()],
            ref_schema: "public".to_owned(),
            ref_table: "p".to_owned(),
            ref_columns: vec!["id".to_owned()],
            on_delete: "NO ACTION".to_owned(),
            on_update: "NO ACTION".to_owned(),
        }];
        let p = table("p", vec![col("id", "int8")]);
        let mut report = Report::default();
        let plan = translate_catalog(&[t, p], &[], &mut report);
        let tp = plan.tables.iter().find(|p| p.basin_name == "t").unwrap();
        let full = tp.create_sql(CreateAttempt::Full);
        assert!(full.contains("CHECK (id > 0)") && full.contains("FOREIGN KEY"));
        let no_checks = tp.create_sql(CreateAttempt::NoChecks);
        assert!(!no_checks.contains("CHECK") && no_checks.contains("FOREIGN KEY"));
        let bare = tp.create_sql(CreateAttempt::NoChecksNoFks);
        assert!(!bare.contains("CHECK") && !bare.contains("FOREIGN KEY"));
        assert_eq!(
            tp.dropped_constraints(CreateAttempt::NoChecksNoFks),
            vec!["CHECK t_pos".to_owned(), "FOREIGN KEY t_p_fkey".to_owned()]
        );
    }

