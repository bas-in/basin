/// How a table's rows travel: PG binary COPY end-to-end, or CSV when any
/// column's binary wire format is outside the Basin decoder's set.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Transfer {
    Binary,
    Csv,
}

impl Transfer {
    pub fn as_str(self) -> &'static str {
        match self {
            Transfer::Binary => "binary",
            Transfer::Csv => "csv",
        }
    }
}

/// One column that survives translation and participates in the data copy.
/// (The full type rendering lives in the table's `column_defs`.)
#[derive(Debug, Clone)]
pub struct PlanColumn {
    pub name: String,
    /// PG-side projection expression (already-quoted; may carry casts or
    /// reshaping like range→JSON or point→WKT).
    pub source_expr: String,
    pub binary_safe: bool,
    /// False for `GENERATED … STORED` columns — present in DDL, excluded
    /// from the COPY column list (Basin computes them).
    pub in_copy: bool,
    /// True when the column became a Basin identity column; the importer
    /// bumps `<table>_<col>_seq` via `setval` after the data lands.
    pub identity_seq: bool,
}

/// Everything the importer needs to create + load one table.
#[derive(Debug, Clone)]
pub struct TablePlan {
    pub source_schema: String,
    pub source_name: String,
    /// Bare name on Basin (flat namespace; schema-prefixed on collision).
    pub basin_name: String,
    pub columns: Vec<PlanColumn>,
    pub transfer: Transfer,
    /// Constraint clauses by severity tier so create can retry with
    /// progressively less optional baggage (see [`TablePlan::create_sql`]).
    pk_clause: Option<String>,
    unique_clauses: Vec<String>,
    check_clauses: Vec<(String, String)>, // (constraint name, rendered clause)
    fk_clauses: Vec<(String, String)>,    // (constraint name, rendered clause)
    /// Column definition lines (without constraints).
    column_defs: Vec<String>,
    /// Which import-plan tables this one references (basin names), for
    /// topological scheduling.
    pub fk_parents: Vec<String>,
}

/// Ladder rung for `CREATE TABLE` retries: each step drops one optional
/// constraint tier and records what was dropped.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum CreateAttempt {
    /// Everything: PK + UNIQUE + CHECK + FK.
    Full,
    /// Drop CHECK constraints (most likely to contain PG-only expressions).
    NoChecks,
    /// Drop CHECKs and FKs (last resort before skipping the table).
    NoChecksNoFks,
}

impl TablePlan {
    /// Render the `CREATE TABLE` for the given retry rung.
    pub fn create_sql(&self, attempt: CreateAttempt) -> String {
        let mut items: Vec<String> = self.column_defs.clone();
        if let Some(pk) = &self.pk_clause {
            items.push(pk.clone());
        }
        items.extend(self.unique_clauses.iter().cloned());
        if attempt == CreateAttempt::Full {
            items.extend(self.check_clauses.iter().map(|(_, c)| c.clone()));
        }
        if attempt != CreateAttempt::NoChecksNoFks {
            items.extend(self.fk_clauses.iter().map(|(_, c)| c.clone()));
        }
        format!(
            "CREATE TABLE {} (\n  {}\n)",
            quote_ident(&self.basin_name),
            items.join(",\n  ")
        )
    }

    pub fn dropped_constraints(&self, attempt: CreateAttempt) -> Vec<String> {
        let mut out = Vec::new();
        if attempt != CreateAttempt::Full {
            out.extend(self.check_clauses.iter().map(|(n, _)| format!("CHECK {n}")));
        }
        if attempt == CreateAttempt::NoChecksNoFks {
            out.extend(
                self.fk_clauses
                    .iter()
                    .map(|(n, _)| format!("FOREIGN KEY {n}")),
            );
        }
        out
    }

    pub fn source_qualified(&self) -> String {
        format!("{}.{}", self.source_schema, self.source_name)
    }

    /// `COPY (SELECT …) TO STDOUT WITH (FORMAT …)` for the source side.
    pub fn copy_out_sql(&self, transfer: Transfer) -> String {
        let exprs: Vec<&str> = self
            .columns
            .iter()
            .filter(|c| c.in_copy)
            .map(|c| c.source_expr.as_str())
            .collect();
        format!(
            "COPY (SELECT {} FROM {}.{}) TO STDOUT WITH (FORMAT {})",
            exprs.join(", "),
            quote_ident(&self.source_schema),
            quote_ident(&self.source_name),
            match transfer {
                Transfer::Binary => "BINARY",
                Transfer::Csv => "CSV",
            }
        )
    }

    /// `COPY t (cols) FROM STDIN WITH (FORMAT …)` for the Basin side.
    pub fn copy_in_sql(&self, transfer: Transfer) -> String {
        let cols: Vec<String> = self
            .columns
            .iter()
            .filter(|c| c.in_copy)
            .map(|c| quote_ident(&c.name))
            .collect();
        format!(
            "COPY {} ({}) FROM STDIN WITH (FORMAT {})",
            quote_ident(&self.basin_name),
            cols.join(", "),
            match transfer {
                Transfer::Binary => "BINARY",
                Transfer::Csv => "CSV",
            }
        )
    }

    /// Identity columns whose backing sequence needs a post-load `setval`.
    pub fn identity_columns(&self) -> Vec<&PlanColumn> {
        self.columns.iter().filter(|c| c.identity_seq).collect()
    }
}

