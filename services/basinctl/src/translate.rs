    #[test]
    fn fk_cycle_is_broken_loudly() {
        let mk_fk = |name: &str, col_: &str, ref_table: &str| SourceFk {
            name: name.to_owned(),
            columns: vec![col_.to_owned()],
            ref_schema: "public".to_owned(),
            ref_table: ref_table.to_owned(),
            ref_columns: vec!["id".to_owned()],
            on_delete: "NO ACTION".to_owned(),
            on_update: "NO ACTION".to_owned(),
        };
        let mut a = table("a", vec![col("id", "int8"), col("b_id", "int8")]);
        a.fks = vec![mk_fk("a_b_fkey", "b_id", "b")];
        let mut b = table("b", vec![col("id", "int8"), col("a_id", "int8")]);
        b.fks = vec![mk_fk("b_a_fkey", "a_id", "a")];
        let mut report = Report::default();
        let plan = translate_catalog(&[a, b], &[], &mut report);
        // Both tables still import (one shared final level), no FKs left.
        assert_eq!(plan.tables.len(), 2);
        assert!(plan.tables.iter().all(|p| p.fk_clauses.is_empty()));
        assert!(report.skips.iter().any(|s| s.reason.contains("cycle")));
    }

