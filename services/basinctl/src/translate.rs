/// Output of [`translate_catalog`]: ordered table plans, enum DDL to run
/// first, and the level schedule for FK-safe parallel data loading.
#[derive(Debug)]
pub struct Plan {
    pub enum_ddl: Vec<String>,
    pub tables: Vec<TablePlan>,
    /// Indices into `tables`, grouped into FK-dependency levels: every
    /// table's FK parents live in an earlier level, so DDL runs level by
    /// level and data loads parallelise *within* a level without tripping
    /// Basin's FK enforcement on ingest.
    pub levels: Vec<Vec<usize>>,
}

/// Translate the introspected catalog. Skips/warnings accumulate in
/// `report`; tables that cannot be imported at all are dropped from the
/// plan (loudly).
pub fn translate_catalog(tables: &[SourceTable], enums: &[EnumType], report: &mut Report) -> Plan {
    // -- Enum DDL (created before any table references one). Basin's
    // namespace for types is flat per project, like tables.
    let mut enum_map: BTreeMap<String, EnumType> = BTreeMap::new();
    let mut enum_ddl = Vec::new();
    for e in enums {
        if enum_map.contains_key(&e.name) {
            report.warn(format!(
                "enum type {}.{} collides with an enum of the same name in another schema; Basin's type namespace is flat — first one wins",
                e.schema, e.name
            ));
            continue;
        }
        let labels: Vec<String> = e.labels.iter().map(|l| quote_literal(l)).collect();
        enum_ddl.push(format!(
            "CREATE TYPE {} AS ENUM ({})",
            quote_ident(&e.name),
            labels.join(", ")
        ));
        enum_map.insert(e.name.clone(), e.clone());
    }

    // -- Basin names: bare table name, schema-prefixed on collision
    // (Basin's schemas are aliases over one flat namespace).
    let mut name_count: HashMap<&str, usize> = HashMap::new();
    for t in tables {
        *name_count.entry(t.name.as_str()).or_default() += 1;
    }
    let basin_name_of = |t: &SourceTable| -> String {
        if name_count[t.name.as_str()] > 1 && t.schema != "public" {
            format!("{}_{}", t.schema, t.name)
        } else {
            t.name.clone()
        }
    };
    let mut basin_names: HashMap<String, String> = HashMap::new(); // qualified -> basin
    for t in tables {
        let bn = basin_name_of(t);
        if bn != t.name {
            report.warn(format!(
                "{} renamed to {bn:?} on Basin (flat namespace; bare name collides across schemas)",
                t.qualified()
            ));
        }
        basin_names.insert(t.qualified(), bn);
    }

    // -- Per-table translation.
    let mut plans: Vec<TablePlan> = Vec::new();
    'tables: for t in tables {
        let table_q = t.qualified();
        let basin_name = basin_names[&table_q].clone();
        let mut column_defs = Vec::new();
        let mut columns = Vec::new();
        let mut kept: HashSet<&str> = HashSet::new();

        for col in &t.columns {
            match map_column(col, &enum_map, report, &table_q) {
                Some((def, binary_safe, expr)) => {
                    kept.insert(col.name.as_str());
                    let is_serial_identity = def.contains("AS IDENTITY");
                    column_defs.push(def);
                    columns.push(PlanColumn {
                        name: col.name.clone(),
                        source_expr: expr,
                        binary_safe,
                        in_copy: col.generated_expr.is_none(),
                        identity_seq: is_serial_identity,
                    });
                }
                None => {
                    // A NOT NULL column without a default cannot be absent
                    // from Basin's COPY column list — the whole table has
                    // to go.
                    if col.not_null && col.default.is_none() {
                        report.skip(
                            "table",
                            &table_q,
                            format!(
                                "column {:?} is NOT NULL without a default and its type cannot be imported",
                                col.name
                            ),
                            Some("relax the column on the source or migrate this table manually"),
                        );
                        continue 'tables;
                    }
                    if t.primary_key.iter().any(|c| c == &col.name) {
                        report.skip(
                            "table",
                            &table_q,
                            format!("primary-key column {:?} cannot be imported", col.name),
                            None,
                        );
                        continue 'tables;
                    }
                }
            }
        }
        if columns.is_empty() {
            report.skip("table", &table_q, "no importable columns", None);
            continue;
        }

        // PK (all PK columns survived — checked above).
        let pk_clause = if t.primary_key.is_empty() {
            None
        } else {
            let cols: Vec<String> = t.primary_key.iter().map(|c| quote_ident(c)).collect();
            Some(format!("PRIMARY KEY ({})", cols.join(", ")))
        };

        // UNIQUE constraints over surviving columns.
        let mut unique_clauses = Vec::new();
        for u in &t.uniques {
            if u.columns.iter().all(|c| kept.contains(c.as_str())) {
                let cols: Vec<String> = u.columns.iter().map(|c| quote_ident(c)).collect();
                unique_clauses.push(format!(
                    "CONSTRAINT {} UNIQUE ({})",
                    quote_ident(&u.name),
                    cols.join(", ")
                ));
            } else {
                report.skip(
                    "constraint",
                    format!("{table_q}.{}", u.name),
                    "UNIQUE references a column that was not imported",
                    None,
                );
            }
        }

        // CHECK constraints: clause text is copied verbatim — it must be
        // Basin-parseable SQL. The create ladder drops them on failure.
        let check_clauses: Vec<(String, String)> = t
            .checks
            .iter()
            .map(|c| {
                (
                    c.name.clone(),
                    format!("CONSTRAINT {} CHECK ({})", quote_ident(&c.name), c.clause),
                )
            })
            .collect();

        // FKs: rewritten to bare Basin table names. FKs pointing outside
        // the import set, self-referential FKs (unsatisfiable during bulk
        // load — Basin has no ALTER TABLE … ADD FOREIGN KEY to defer
        // them), and FKs over skipped columns are dropped with a report.
        let mut fk_clauses = Vec::new();
        let mut fk_parents = Vec::new();
        for fk in &t.fks {
            let fk_obj = format!("{table_q}.{}", fk.name);
            let ref_q = format!("{}.{}", fk.ref_schema, fk.ref_table);
            let Some(ref_basin) = basin_names.get(&ref_q) else {
                report.skip(
                    "constraint",
                    fk_obj,
                    format!("FOREIGN KEY references {ref_q}, which is not part of this import"),
                    Some("import the referenced table in the same run to keep the constraint"),
                );
                continue;
            };
            if ref_q == table_q {
                report.skip(
                    "constraint",
                    fk_obj,
                    "self-referential FOREIGN KEY cannot be enforced during bulk load (Basin has no ALTER TABLE … ADD FOREIGN KEY)",
                    Some("re-add manually is not yet possible; rows import without the constraint"),
                );
                continue;
            }
            if !fk.columns.iter().all(|c| kept.contains(c.as_str())) {
                report.skip(
                    "constraint",
                    fk_obj,
                    "FOREIGN KEY references a column that was not imported",
                    None,
                );
                continue;
            }
            let cols: Vec<String> = fk.columns.iter().map(|c| quote_ident(c)).collect();
            let ref_cols: Vec<String> = fk.ref_columns.iter().map(|c| quote_ident(c)).collect();
            let mut clause = format!(
                "CONSTRAINT {} FOREIGN KEY ({}) REFERENCES {} ({})",
                quote_ident(&fk.name),
                cols.join(", "),
                quote_ident(ref_basin),
                ref_cols.join(", ")
            );
            if fk.on_delete != "NO ACTION" {
                let _ = write!(clause, " ON DELETE {}", fk.on_delete);
            }
            if fk.on_update != "NO ACTION" {
                let _ = write!(clause, " ON UPDATE {}", fk.on_update);
            }
            fk_clauses.push((fk.name.clone(), clause));
            fk_parents.push(ref_basin.clone());
        }

        let transfer = if columns.iter().filter(|c| c.in_copy).all(|c| c.binary_safe) {
            Transfer::Binary
        } else {
            Transfer::Csv
        };

        plans.push(TablePlan {
            source_schema: t.schema.clone(),
            source_name: t.name.clone(),
            basin_name,
            columns,
            transfer,
            pk_clause,
            unique_clauses,
            check_clauses,
            fk_clauses,
            column_defs,
            fk_parents,
        });
    }

    let levels = topo_levels(&mut plans, report);
    Plan {
        enum_ddl,
        tables: plans,
        levels,
    }
}

/// Group table indices into FK-dependency levels (parents strictly earlier).
/// FK cycles are broken by dropping the in-cycle FKs (loudly) and putting
/// the remainder in one final level.
fn topo_levels(plans: &mut [TablePlan], report: &mut Report) -> Vec<Vec<usize>> {
    let index_of: HashMap<String, usize> = plans
        .iter()
        .enumerate()
        .map(|(i, p)| (p.basin_name.clone(), i))
        .collect();
    let mut level: Vec<Option<usize>> = vec![None; plans.len()];
    let mut levels: Vec<Vec<usize>> = Vec::new();
    loop {
        let mut placed_any = false;
        let mut this_level = Vec::new();
        for i in 0..plans.len() {
            if level[i].is_some() {
                continue;
            }
            let ready = plans[i]
                .fk_parents
                .iter()
                .all(|p| index_of.get(p).map(|&j| level[j].is_some()).unwrap_or(true));
            if ready {
                this_level.push(i);
                placed_any = true;
            }
        }
        if !placed_any {
            break;
        }
        for &i in &this_level {
            level[i] = Some(levels.len());
        }
        levels.push(this_level);
    }
    // Anything unplaced sits on an FK cycle: drop its FKs, warn, final level.
    let remaining: Vec<usize> = (0..plans.len()).filter(|&i| level[i].is_none()).collect();
    if !remaining.is_empty() {
        for &i in &remaining {
            let names: Vec<String> = plans[i].fk_clauses.iter().map(|(n, _)| n.clone()).collect();
            report.skip(
                "constraint",
                format!("{} ({})", plans[i].source_qualified(), names.join(", ")),
                "FOREIGN KEY participates in a reference cycle; dropped to allow bulk load",
                None,
            );
            plans[i].fk_clauses.clear();
            plans[i].fk_parents.clear();
        }
        levels.push(remaining);
    }
    levels
}

