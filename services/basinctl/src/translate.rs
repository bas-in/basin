/// Result of mapping one source column's type.
enum Mapped {
    Ok {
        basin_type: String,
        binary_safe: bool,
        /// Optional PG-side cast/reshape; `{}` is replaced with the quoted
        /// column reference.
        expr_template: Option<String>,
        warning: Option<String>,
    },
    Unsupported {
        reason: String,
        hint: Option<String>,
    },
}

fn ok(basin_type: impl Into<String>, binary_safe: bool) -> Mapped {
    Mapped::Ok {
        basin_type: basin_type.into(),
        binary_safe,
        expr_template: None,
        warning: None,
    }
}

fn ok_expr(basin_type: impl Into<String>, binary_safe: bool, tpl: &str) -> Mapped {
    Mapped::Ok {
        basin_type: basin_type.into(),
        binary_safe,
        expr_template: Some(tpl.to_owned()),
        warning: None,
    }
}

fn unsupported(reason: impl Into<String>, hint: Option<&str>) -> Mapped {
    Mapped::Unsupported {
        reason: reason.into(),
        hint: hint.map(str::to_owned),
    }
}

/// Extract `(precision, scale)` rendered for NUMERIC, clamping to Basin's
/// Decimal128 ceiling of 38. Bare `numeric` (no typmod) becomes
/// `NUMERIC(38, 18)` — Basin's bare NUMERIC is `(38, 0)`, which would
/// truncate fractional digits.
fn numeric_type(col: &SourceColumn) -> (String, Option<String>, Option<String>) {
    match (col.num_precision, col.num_scale) {
        (Some(p), s) if p >= 1 && p <= 38 => {
            let s = s.unwrap_or(0).clamp(0, p);
            (format!("NUMERIC({p}, {s})"), None, None)
        }
        (Some(p), s) => {
            // Precision beyond Decimal128 — clamp + cast, warn loudly.
            let s = s.unwrap_or(0).clamp(0, 37);
            (
                format!("NUMERIC(38, {s})"),
                Some(format!("{{}}::numeric(38, {s})")),
                Some(format!(
                    "numeric({p}, …) exceeds Basin's NUMERIC(38) ceiling; clamped to NUMERIC(38, {s}) — values needing more than 38 digits will fail the source-side cast"
                )),
            )
        }
        (None, _) => (
            "NUMERIC(38, 18)".to_owned(),
            Some("{}::numeric(38, 18)".to_owned()),
            Some(
                "bare numeric has no fixed precision in Postgres; mapped to NUMERIC(38, 18) — values with more than 20 integer digits will fail the source-side cast"
                    .to_owned(),
            ),
        ),
    }
}

/// Map one base (non-array) udt to Basin. `enums` carries the importable
/// enum types keyed by source type name.
fn map_base_type(
    col: &SourceColumn,
    udt: &str,
    typtype: &str,
    enums: &BTreeMap<String, EnumType>,
) -> Mapped {
    // Enums pass through: the importer emits `CREATE TYPE … AS ENUM` on
    // Basin before any table that uses one. Binary-safe — PG's enum_send
    // is the label text, which Basin decodes as TEXT for the enum-backed
    // Utf8 column.
    if typtype == "e" {
        return if enums.contains_key(udt) {
            ok(quote_ident(udt), true)
        } else {
            unsupported(
                format!("enum type {udt:?} was not found in the source catalog scan"),
                None,
            )
        };
    }
    if typtype == "c" {
        return unsupported(
            "composite types are not supported by Basin",
            Some("flatten the composite into scalar columns or store it as JSONB"),
        );
    }

    match udt {
        "int2" => ok("SMALLINT", true),
        "int4" => ok("INTEGER", true),
        "int8" => ok("BIGINT", true),
        "float4" => ok("REAL", true),
        "float8" => ok("DOUBLE PRECISION", true),
        "bool" => ok("BOOLEAN", true),
        "text" | "name" => ok("TEXT", true),
        "varchar" => match col.max_len {
            Some(n) => ok(format!("VARCHAR({n})"), true),
            None => ok("TEXT", true),
        },
        "bpchar" => match col.max_len {
            Some(n) => ok(format!("CHAR({n})"), true),
            None => ok("TEXT", true),
        },
        "numeric" => {
            let (ty, tpl, warning) = numeric_type(col);
            Mapped::Ok {
                basin_type: ty,
                binary_safe: true,
                expr_template: tpl,
                warning,
            }
        }
        "bytea" => ok("BYTEA", true),
        "date" => ok("DATE", true),
        // TIME's int8-micros binary format is not in Basin's binary COPY
        // codec set (Time64 is missing from validate_binary_copy_columns)
        // — ship it as CSV text.
        "time" => ok("TIME", false),
        "timetz" => unsupported(
            "TIME WITH TIME ZONE is not supported by Basin",
            Some("store as TIME (shift to a fixed zone) or as TEXT"),
        ),
        "timestamp" => ok("TIMESTAMP", true),
        "timestamptz" => ok("TIMESTAMPTZ", true),
        "interval" => Mapped::Ok {
            basin_type: "INTERVAL".to_owned(),
            binary_safe: false,
            expr_template: None,
            warning: Some(
                "interval values travel as Postgres text form; verify a sample after import"
                    .to_owned(),
            ),
        },
        "uuid" => ok("UUID", true),
        "jsonb" => ok("JSONB", true),
        // json: Basin treats JSON as a JSONB synonym (canonicalised). Cast
        // to jsonb on the source so the binary wire format (versioned
        // jsonb_send) matches what Basin's JSONB decoder expects.
        "json" => Mapped::Ok {
            basin_type: "JSONB".to_owned(),
            binary_safe: true,
            expr_template: Some("{}::jsonb".to_owned()),
            warning: Some(
                "json column mapped to JSONB — Basin canonicalises (key order / whitespace not preserved)"
                    .to_owned(),
            ),
        },
        "citext" => ok("CITEXT", true),
        "xml" => ok("XML", true),
        "money" => Mapped::Ok {
            basin_type: "MONEY".to_owned(),
            binary_safe: false,
            // money's binary format is a bare int8 and its text form is
            // locale-decorated ("$1,000.00"); cast through numeric so the
            // CSV cell is a plain decimal Basin's MONEY (Decimal128(20,2))
            // ingest accepts.
            expr_template: Some("{}::numeric".to_owned()),
            warning: None,
        },
        "inet" => ok("INET", false),
        "cidr" => ok("CIDR", false),
        "macaddr" => ok("MACADDR", false),
        "macaddr8" => ok("MACADDR8", false),
        "bit" => match col.max_len {
            Some(n) => ok(format!("BIT({n})"), false),
            None => ok("BIT", false),
        },
        "varbit" => ok("VARBIT", false),
        "tsvector" => ok("TSVECTOR", false),
        "tsquery" => ok("TSQUERY", false),
        // Ranges: Basin stores ranges as a JSON object
        // {"l":…,"u":…,"li":…,"ui":…}. Reshape on the source so the stored
        // form matches what Basin's range operators read. NULL bound =
        // infinite on both sides.
        "int4range" | "int8range" | "numrange" | "daterange" | "tsrange" | "tstzrange" => {
            let tpl = "CASE WHEN {} IS NULL THEN NULL ELSE json_build_object('l', lower({}), 'u', upper({}), 'li', lower_inc({}), 'ui', upper_inc({}))::text END";
            Mapped::Ok {
                basin_type: udt.to_uppercase(),
                binary_safe: false,
                expr_template: Some(tpl.to_owned()),
                warning: Some(
                    "range column reshaped to Basin's JSON range encoding; empty ranges are not representable and will import as their bound pair"
                        .to_owned(),
                ),
            }
        }
        // pgvector — pass through with the dimension recovered from
        // format_type ("vector(384)"); pgvector's text form `[0.1,0.2]`
        // is what Basin's vector ingest parses.
        "vector" => match vector_dim(&col.formatted_type) {
            Some(d) => ok_expr(format!("VECTOR({d})"), false, "{}::text"),
            None => unsupported(
                "vector column has no fixed dimension (bare `vector`)",
                Some("ALTER the source column to vector(N) first — Basin requires a fixed dimension"),
            ),
        },
        // Native PG point → Basin POINT (WKT text form on the wire).
        "point" => ok_expr(
            "POINT",
            false,
            "CASE WHEN {} IS NULL THEN NULL ELSE 'POINT(' || ({})[0]::text || ' ' || ({})[1]::text || ')' END",
        ),
        // PostGIS geometry: only the Point subtype exists in Basin.
        "geometry" => match geometry_subtype(&col.formatted_type) {
            Some((subtype, srid)) if subtype.eq_ignore_ascii_case("point") => {
                let basin = match srid {
                    Some(s) => format!("GEOMETRY(POINT, {s})"),
                    None => "GEOMETRY(POINT)".to_owned(),
                };
                ok_expr(basin, false, "ST_AsText({})")
            }
            Some((subtype, _)) => unsupported(
                format!("PostGIS geometry subtype {subtype:?} is not supported (Basin supports POINT only)"),
                Some("store as WKT TEXT or split into POINT columns"),
            ),
            None => unsupported(
                "untyped PostGIS geometry column (no subtype modifier)",
                Some("Basin supports GEOMETRY(POINT[, srid]) only"),
            ),
        },
        other => unsupported(
            format!("type {other:?} ({}) has no Basin mapping", col.formatted_type),
            None,
        ),
    }
}

/// Pull `N` out of `vector(N)`.
fn vector_dim(formatted: &str) -> Option<u32> {
    let inner = formatted.strip_prefix("vector(")?.strip_suffix(')')?;
    inner.trim().parse().ok()
}

/// Pull `(subtype, srid)` out of `geometry(Point,4326)` / `geometry(Point)`.
fn geometry_subtype(formatted: &str) -> Option<(String, Option<u32>)> {
    let inner = formatted.strip_prefix("geometry(")?.strip_suffix(')')?;
    let mut parts = inner.splitn(2, ',');
    let subtype = parts.next()?.trim().to_owned();
    let srid = parts.next().and_then(|s| s.trim().parse().ok());
    Some((subtype, srid))
}

/// Map a whole column, including array / domain / serial / identity
/// handling. Returns `(basin type rendering, binary_safe, source expr)`.
fn map_column(
    col: &SourceColumn,
    enums: &BTreeMap<String, EnumType>,
    report: &mut Report,
    table_q: &str,
) -> Option<(String, bool, String)> {
    let colref = quote_ident(&col.name);
    let object = format!("{table_q}.{}", col.name);

    if let Some(domain) = &col.domain_name {
        report.warn(format!(
            "{object}: domain {domain:?} flattened to its underlying type ({})",
            col.formatted_type
        ));
    }

    // Arrays: map the element type, require it to be a supported scalar.
    // PG's array text form `{…}` rides CSV (array binary format is not in
    // Basin's codec set).
    if col.data_type == "ARRAY" {
        let elem_udt = col.elem_udt.clone().unwrap_or_default();
        let elem_typtype = col.elem_typtype.clone().unwrap_or_else(|| "b".to_owned());
        let mut elem_col = col.clone();
        // Element typmods (varchar(10)[]) are not split out by
        // information_schema; map the bare element type.
        elem_col.max_len = None;
        match map_base_type(&elem_col, &elem_udt, &elem_typtype, enums) {
            Mapped::Ok { basin_type, .. } => {
                report.warn(format!(
                    "{object}: array values travel as Postgres array literals; verify a sample after import"
                ));
                let mut def = format!("{colref} {basin_type}[]");
                if col.not_null {
                    def.push_str(" NOT NULL");
                }
                return Some((def, false, colref));
            }
            Mapped::Unsupported { reason, hint } => {
                report.skip(
                    "column",
                    object,
                    format!("array of unsupported element type: {reason}"),
                    hint.as_deref(),
                );
                return None;
            }
        }
    }

    // serial / bigserial / smallserial: information_schema shows them as
    // plain ints with a nextval(...) default. Normalise to Basin's identity
    // convention at BIGINT width; cast the outgoing stream to int8 so the
    // binary wire matches the widened column.
    let is_serial = col
        .default
        .as_deref()
        .map(|d| d.trim_start().starts_with("nextval("))
        .unwrap_or(false)
        && matches!(col.udt_name.as_str(), "int2" | "int4" | "int8");
    if is_serial {
        let rendered = format!("{colref} BIGINT GENERATED BY DEFAULT AS IDENTITY");
        return Some((rendered, true, format!("{colref}::int8")));
    }

    let mapped = map_base_type(col, &col.udt_name, &col.typtype, enums);
    let (basin_type, binary_safe, expr_template, warning) = match mapped {
        Mapped::Ok {
            basin_type,
            binary_safe,
            expr_template,
            warning,
        } => (basin_type, binary_safe, expr_template, warning),
        Mapped::Unsupported { reason, hint } => {
            report.skip("column", object, reason, hint.as_deref());
            return None;
        }
    };
    if let Some(w) = warning {
        report.warn(format!("{object}: {w}"));
    }

    let expr = match expr_template {
        Some(tpl) => tpl.replace("{}", &colref),
        None => colref.clone(),
    };

    // Assemble the column definition.
    let mut def = format!("{colref} {basin_type}");
    if let Some(gen) = &col.generated_expr {
        let _ = write!(def, " GENERATED ALWAYS AS ({gen}) STORED");
        report.warn(format!(
            "{object}: generated-column expression copied verbatim; it must be valid Basin SQL (recomputed on Basin, excluded from the data copy)"
        ));
    } else if let Some(kind) = col.identity {
        def.push_str(match kind {
            IdentityKind::Always => " GENERATED ALWAYS AS IDENTITY",
            IdentityKind::ByDefault => " GENERATED BY DEFAULT AS IDENTITY",
        });
        // Identity sequence options (START / INCREMENT) are not supported
        // by Basin and are not carried over; the importer setval()s past
        // MAX(col) after load, which is what matters for inserts.
    } else {
        if col.not_null {
            def.push_str(" NOT NULL");
        }
        if let Some(d) = &col.default {
            if let Some(rendered) = translate_default(d) {
                let _ = write!(def, " DEFAULT {rendered}");
            } else {
                report.warn(format!(
                    "{object}: DEFAULT {d:?} dropped — not in the importer's portable-default set (literals, now()/CURRENT_TIMESTAMP/CURRENT_DATE, gen_random_uuid()/uuid_generate_v4())"
                ));
            }
        }
    }

    Some((def, binary_safe, expr))
}

/// Translate a PG column default into something Basin's DDL accepts, or
/// `None` to drop it (with a warning at the call site). Deliberately a
/// small allowlist: literals, the current-time family, and UUID
/// generation. Everything else is PG-flavoured enough that carrying it
/// over silently would be a lie.
fn translate_default(default: &str) -> Option<String> {
    let d = default.trim();
    // `'lit'::type` — strip the cast, keep the literal.
    let base = match d.find("'::") {
        Some(idx) if d.starts_with('\'') => &d[..=idx],
        _ => d,
    };
    let lower = base.to_ascii_lowercase();
    if lower == "null" || lower.starts_with("null::") {
        return None; // NULL default == no default
    }
    if base.starts_with('\'') && base.ends_with('\'') && base.len() >= 2 {
        return Some(base.to_owned());
    }
    if lower == "true" || lower == "false" {
        return Some(lower);
    }
    if base.parse::<f64>().is_ok() {
        return Some(base.to_owned());
    }
    match lower.as_str() {
        "now()" | "current_timestamp" => Some("now()".to_owned()),
        "current_date" => Some("CURRENT_DATE".to_owned()),
        "gen_random_uuid()" => Some("gen_random_uuid()".to_owned()),
        "uuid_generate_v4()" => Some("uuid_generate_v4()".to_owned()),
        _ => None,
    }
}

