//! Regression tests for SQL shapes real ORMs emit that previously failed.
//!
//! Each test reproduces a specific live-ORM failure mode against the engine
//! directly (no pgwire), so it runs in CI without the ORM's own toolchain:
//!
//! - Drizzle `INSERT INTO t (id, …) VALUES (default, …)` on a SERIAL/identity
//!   column — the explicit `DEFAULT` keyword must draw the next sequence value,
//!   not NULL.
//! - SQLAlchemy `INSERT INTO t (…) SELECT …` into a narrow (Int32) identity PK —
//!   the synthesized i64 identity values must cast to the column's type.
//! - Django `F()` UPDATE — `SET col = "t"."col" + 1` carries a table qualifier
//!   that must be stripped so it resolves against the update's temp table.
//! - Schema-qualified FK reference (`REFERENCES "public"."u" (id)`) in both
//!   `CREATE TABLE` and `ALTER TABLE … ADD CONSTRAINT` — accepted by taking the
//!   bare table name.

#![allow(clippy::print_stdout)]

use std::sync::Arc;

use arrow_array::{Array, Int32Array, Int64Array};
use basin_catalog::InMemoryCatalog;
use basin_common::ProjectId;
use basin_engine::{Engine, EngineConfig, ExecResult};
use object_store::local::LocalFileSystem;
use tempfile::TempDir;

async fn engine_in(dir: &TempDir) -> Engine {
    let fs = LocalFileSystem::new_with_prefix(dir.path()).unwrap();
    let storage = basin_storage::Storage::new(basin_storage::StorageConfig {
        object_store: Arc::new(fs),
        root_prefix: None,
        disk_cache: basin_integration_tests::cache_defaults::default_test_disk_cache(),
        page_cache: basin_integration_tests::cache_defaults::default_test_page_cache(),
    });
    let catalog: Arc<dyn basin_catalog::Catalog> = Arc::new(InMemoryCatalog::new());
    Engine::new(EngineConfig {
        storage,
        catalog,
        shard: None,
    })
}

fn ids_i64(batches: &[arrow_array::RecordBatch], name: &str) -> Vec<i64> {
    let mut out = Vec::new();
    for b in batches {
        let arr = b
            .column_by_name(name)
            .unwrap_or_else(|| panic!("missing column {name}"))
            .as_any()
            .downcast_ref::<Int64Array>()
            .unwrap_or_else(|| panic!("column {name} is not Int64"));
        for i in 0..arr.len() {
            if !arr.is_null(i) {
                out.push(arr.value(i));
            }
        }
    }
    out
}

