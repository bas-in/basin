//! IDENTITY columns + SERIAL/BIGSERIAL/SMALLSERIAL syntactic sugar.
//!
//! Bar: every shape below runs end-to-end against the engine — CREATE
//! TABLE mints a backing sequence, INSERT auto-fills omitted IDENTITY
//! columns from nextval, GENERATED ALWAYS rejects user-supplied values
//! unless OVERRIDING SYSTEM VALUE is set, OVERRIDING USER VALUE on a BY
//! DEFAULT column discards the user's literal and re-fills from nextval.
//!
//! Forms exercised:
//!
//! ```sql
//! CREATE TABLE a (id BIGINT GENERATED ALWAYS AS IDENTITY, name TEXT);
//! INSERT INTO a (name) VALUES ('x'), ('y');        -- id=1, id=2
//! INSERT INTO a (id, name) VALUES (99, 'z');       -- REJECTED
//! INSERT INTO a (id, name) OVERRIDING SYSTEM VALUE VALUES (99, 'z');  -- OK
//!
//! CREATE TABLE b (id INT GENERATED BY DEFAULT AS IDENTITY, name TEXT);
//! INSERT INTO b (id, name) VALUES (10, 'p');       -- accepts literal
//! INSERT INTO b (name) VALUES ('q');               -- auto-fills nextval
//! INSERT INTO b (id, name) OVERRIDING USER VALUE VALUES (99, 'r');  -- discards 99
//!
//! CREATE TABLE c (id SERIAL, name TEXT);
//! INSERT INTO c (id, name) VALUES (5, 's');        -- accepts literal (BY DEFAULT)
//! INSERT INTO c (name) VALUES ('t');               -- auto-fills nextval
//!
//! CREATE TABLE d (id BIGSERIAL, name TEXT);  -- BIGSERIAL variant
//! CREATE TABLE e (id SMALLSERIAL, name TEXT); -- SMALLSERIAL variant
//!
//! UPDATE a SET id = 5 WHERE name = 'x';            -- REJECTED (ALWAYS)
//! ```

#![allow(clippy::print_stdout)]

use std::sync::Arc;

use arrow_array::Int64Array;
use basin_catalog::InMemoryCatalog;
use basin_common::TenantId;
use basin_engine::{Engine, EngineConfig, ExecResult};
use object_store::local::LocalFileSystem;
use tempfile::TempDir;

fn rows_int64(batches: &[arrow_array::RecordBatch], name: &str) -> Vec<i64> {
    let mut out = Vec::new();
    for b in batches {
        let arr = b
            .column_by_name(name)
            .unwrap_or_else(|| panic!("missing column {name}"))
            .as_any()
            .downcast_ref::<Int64Array>()
            .unwrap_or_else(|| panic!("column {name} is not Int64"));
        for i in 0..arr.len() {
            if arr.is_null(i) {
                continue;
            }
            out.push(arr.value(i));
        }
    }
    out
}

async fn engine_in(dir: &TempDir) -> Engine {
    let fs = LocalFileSystem::new_with_prefix(dir.path()).unwrap();
    let storage = basin_storage::Storage::new(basin_storage::StorageConfig {
        object_store: Arc::new(fs),
        root_prefix: None,
        disk_cache: basin_integration_tests::cache_defaults::default_test_disk_cache(),
        page_cache: basin_integration_tests::cache_defaults::default_test_page_cache(),
    });
    let catalog: Arc<dyn basin_catalog::Catalog> = Arc::new(InMemoryCatalog::new());
    Engine::new(EngineConfig {
        storage,
        catalog,
        shard: None,
    })
}

/// `CREATE TABLE t (id BIGINT GENERATED ALWAYS AS IDENTITY, name TEXT)` —
/// omitted-column INSERT fills from nextval (1, 2). Literal INSERT is
/// rejected unless OVERRIDING SYSTEM VALUE.
#[tokio::test]
async fn identity_always_omitted_fills_from_nextval() {
    let dir = TempDir::new().unwrap();
    let engine = engine_in(&dir).await;
    let sess = engine.open_session(TenantId::new()).await.unwrap();

    sess.execute("CREATE TABLE t (id BIGINT GENERATED ALWAYS AS IDENTITY, name TEXT NOT NULL)")
        .await
        .expect("CREATE TABLE with IDENTITY ALWAYS");

    sess.execute("INSERT INTO t (name) VALUES ('a'), ('b')")
        .await
        .expect("INSERT with id omitted");

    let res = sess
        .execute("SELECT id, name FROM t ORDER BY id")
        .await
        .unwrap();
    match res {
        ExecResult::Rows { batches, .. } => {
            assert_eq!(rows_int64(&batches, "id"), vec![1, 2]);
        }
        other => panic!("unexpected: {other:?}"),
    }
}

#[tokio::test]
