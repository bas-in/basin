/// Two IDENTITY-style sequences on different tables coexist without
/// stepping on each other's namespace — important because the implicit
/// `<table>_<col>_seq` name is per-table.
#[tokio::test]
async fn two_identity_tables_have_independent_sequences() {
    let dir = TempDir::new().unwrap();
    let engine = engine_in(&dir).await;
    let sess = engine.open_session(TenantId::new()).await.unwrap();

    sess.execute("CREATE TABLE t (id BIGINT GENERATED ALWAYS AS IDENTITY, name TEXT NOT NULL)")
        .await
        .unwrap();
    sess.execute("CREATE TABLE u (id BIGINT GENERATED ALWAYS AS IDENTITY, name TEXT NOT NULL)")
        .await
        .unwrap();
    sess.execute("INSERT INTO t (name) VALUES ('a'), ('b')")
        .await
        .unwrap();
    sess.execute("INSERT INTO u (name) VALUES ('p')")
        .await
        .unwrap();
    sess.execute("INSERT INTO t (name) VALUES ('c')")
        .await
        .unwrap();

    let res = sess
        .execute("SELECT id FROM t ORDER BY id")
        .await
        .unwrap();
    match res {
        ExecResult::Rows { batches, .. } => {
            assert_eq!(rows_int64(&batches, "id"), vec![1, 2, 3]);
        }
        other => panic!("unexpected: {other:?}"),
    }
    let res = sess.execute("SELECT id FROM u").await.unwrap();
    match res {
        ExecResult::Rows { batches, .. } => {
            assert_eq!(rows_int64(&batches, "id"), vec![1]);
        }
        other => panic!("unexpected: {other:?}"),
    }
}
