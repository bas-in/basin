#[tokio::test]
async fn identity_by_default_accepts_user_value() {
    let dir = TempDir::new().unwrap();
    let engine = engine_in(&dir).await;
    let sess = engine.open_session(TenantId::new()).await.unwrap();

    sess.execute(
        "CREATE TABLE t (id BIGINT GENERATED BY DEFAULT AS IDENTITY, name TEXT NOT NULL)",
    )
    .await
    .expect("CREATE TABLE with IDENTITY BY DEFAULT");

    // Literal accepted.
    sess.execute("INSERT INTO t (id, name) VALUES (10, 'a')")
        .await
        .expect("BY DEFAULT IDENTITY accepts literal");
    // Omitted → nextval.
    sess.execute("INSERT INTO t (name) VALUES ('b')")
        .await
        .expect("BY DEFAULT IDENTITY auto-fills");

    let res = sess
        .execute("SELECT id, name FROM t ORDER BY name")
        .await
        .unwrap();
    match res {
        ExecResult::Rows { batches, .. } => {
            let ids = rows_int64(&batches, "id");
            assert_eq!(ids.len(), 2);
            assert_eq!(ids[0], 10);
            // The nextval-filled row gets the sequence's first value (1).
            assert_eq!(ids[1], 1);
        }
        other => panic!("unexpected: {other:?}"),
    }
}

#[tokio::test]
